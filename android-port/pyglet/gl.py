"""OpenGL 1.x on Android, backed by gl4es.

GENERATED by tools/generate_gl_shim.py from pyglet 1.5.31 - do not edit.

The game is written against desktop OpenGL 1.x: a matrix stack, display
lists, fixed-function lighting, fog, alpha test, GL_QUADS and client-side
vertex arrays. Android exposes only OpenGL ES, where none of that exists.
gl4es implements GL 1.5 over GLES2, so this module is a ctypes binding to
it rather than an emulation of it.

Importing this module must not touch GL: the game's Cython modules import
pyglet.gl at their own import time, long before a context exists, and that
is exactly what crashed the first APK. Call initialize() once the context
is current instead.
"""

